#pragma once
// ============================================================================
// reduce.cuh —— 一维归约（求和）算子的接口声明
//
// 文件职责
//   本文件只放置“声明”与接口约定，所有实现见同目录 reduce.cu。
//   算子使用者只需包含本头文件，即可调用 CPU 参考实现与 GPU 归约内核。
//   算子自身的测试与本接口文件解耦，按职责拆分在三个文件中：
//     test.cuh  可复用测试驱动 test_reduce_kernel 的声明
//     test.cu   上述测试驱动的实现
//     main.cu   执行入口：把被测内核注册给测试驱动并运行
//
// 归约语义（当前阶段：一维整体求和）
//   输入：一维 fp32 数组 input[0, n)；输出：整个数组的和（标量）。
//   参考实现 reduce_cpu 在主机端逐元素累加；GPU 采用两阶段归约：
//     阶段 1：每个 block 把自己负责的一段元素归约为“部分和”，
//             写入 output[blockIdx.x]（故 output 至少要有 grid 个元素）；
//     阶段 2：由调用方把 grid 个部分和再汇总一次，得到最终标量。
//
// 版本规划（实现现状）
//   v0 交错寻址共享内存归约（interleaved addressing）——正确性基线。
//   v1 连续寻址共享内存归约（consecutive addressing）——把 v0 每轮的
//      活跃线程从“交错间隔”改为“连续前缀”，消除 warp 内分歧。
//   后续版本（v2 每线程多元素 + float4 向量化、v3 反向步长等）将保持与
//   v0/v1 完全一致的 ReduceKernel 签名与启动模型，从而可被 test.cuh /
//   test.cu 中的同一套测试驱动直接复用（只需在 main.cu 更换内核名）。
//
// 正确性口径见 docs/benchmark-methodology.md：Reduce 相对误差容差 1e-3。
// ============================================================================

#include <cuda_runtime.h>  // __global__、cudaError_t 等 CUDA 基本定义

// ---------------------------------------------------------------------------
// CPU 参考实现（主机端正确性基线）
// ---------------------------------------------------------------------------
// 对 input[0, n) 逐元素累加求和。内部使用 double 累加，以抑制长序列 fp32
// 顺序累加不断放大的舍入误差（docs 说明：4096 项顺序累加即可达 ~1e-4 量级）；
// 返回时再转回 float，便于与 GPU 的 fp32 结果做同类型比较。
float reduce_cpu(const float* input, int n);

// ---------------------------------------------------------------------------
// GPU 归约内核 v0（交错寻址共享内存归约）
// ---------------------------------------------------------------------------
// 每个 block 负责一段连续元素并归约出 1 个部分和，写入 output[blockIdx.x]。
// 分段方式：block k 负责全局下标 [k*blockDim.x, (k+1)*blockDim.x)，
// 因此块内采用“每线程搬运 1 个元素 + 共享内存树形归约”。
//
// 启动约束（由调用方保证）：
//   * grid >= ceil(n / block)，使每个输入元素恰好被一个线程读到；
//   * block 应为 2 的幂（默认 256），保证树形归约各轮可以均匀配对；
//   * 需要申请 block * sizeof(float) 字节的动态共享内存
//     （内核用 extern __shared__ 声明，大小由启动配置的第三参数指定）。
__global__ void reduce_v0(const float* input, float* output, int n);

// ---------------------------------------------------------------------------
// GPU 归约内核 v1（连续寻址共享内存归约）
// ---------------------------------------------------------------------------
// 网格/块模型、输出约定与启动约束和 v0 完全一致（每 block 一段连续元素 →
// 1 个部分和写入 output[blockIdx.x]），差异只在块内树形归约的寻址方式：
//   * v0：活跃线程条件 tid % (2*step) == 0，交错分布，存在 warp 内分歧；
//   * v1：活跃线程是连续前缀 tid < blockDim.x/(2*step)（等价地
//          index = tid*2*step < blockDim.x），整条 warp 全活跃或全空闲，
//          warp 内无分歧。
// 详细推导、示例与注意事项见 reduce.cu 中本内核的定义处注释。
__global__ void reduce_v1(const float* input, float* output, int n);

// ---------------------------------------------------------------------------
// 归约内核的统一签名
// ---------------------------------------------------------------------------
// 各版本 GPU 归约内核均按 (const float* 输入, float* 部分和输出, int 长度)
// 组织：先写出各 block 的部分和，再由调用方汇总为最终标量。
// 约定各版本签名完全一致，是为了让 test.cuh / test.cu 中的测试驱动可以“接收
// 内核函数指针”从而对任意版本复用同一套测试代码（对应旧版 Reduce/src/reduce.cu
// 的 testReduceKernel，见学习笔记 §14）。
using ReduceKernel = void (*)(const float* input, float* output, int n);
// ============================ reduce.cuh end ===============================
